#!/bin/bash
# ============================================================
# Wrapper Script برای اجرای زمان‌بندی‌شده اسکنر کریپتو
# این اسکریپت توسط cron فراخوانی می‌شود
# متغیرهای محیطی را از فایل .env بارگذاری می‌کند
# ============================================================

# مسیر پروژه
SCANNER_DIR="/home/z/my-project/download/crypto_scanner"
PYTHON_BIN="/usr/bin/python3"

# بارگذاری متغیرهای محیطی از فایل .env
if [ -f "$SCANNER_DIR/.env" ]; then
    set -a
    source "$SCANNER_DIR/.env"
    set +a
fi

# تنظیم منطقه زمانی تهران
export TZ='Asia/Tehran'

# تاریخ و زمان فعلی (تهران)
CURRENT_TIME=$(date '+%Y-%m-%d %H:%M:%S %Z')
echo "============================================================"
echo "[$CURRENT_TIME] شروع اجرای اسکنر کریپتو"
echo "============================================================"

# اجرای اسکنر
cd "$SCANNER_DIR" && $PYTHON_BIN run_scheduled.py

EXIT_CODE=$?
echo "============================================================"
echo "[$(date '+%Y-%m-%d %H:%M:%S %Z')] پایان - کد خروج: $EXIT_CODE"
echo "============================================================"
exit $EXIT_CODE
